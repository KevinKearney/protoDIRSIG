def phase_hyper_native(st):
    return [s for s in st.s2s if s.startswith("s2s3-phase-hyperresolved-") and "-r100km-" not in s]


def phase_unres(st):
    return [s for s in st.s2s if s.startswith("s2s3-phase-unresolved-a")]


def _window(st, key):
    """The image sum at the small window over the native record's (the same geometry and exposure)."""
    w, n = WINDOW_PAIRS[key]
    return st.s2s[w]["measured"] / st.s2s[n]["measured"], [w, n]


WORDS = ("zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve")
WITHIN_MIN_PX = 2.0


def _within_one(st):
    """Records of 2 px and up, still or singly moving, within the TOL_FLUX_ENVELOPE row: the largest flux deficit."""
    specs = [r["spec"] for r, a, key, why in st.rows if not why and a["size_px"] >= WITHIN_MIN_PX and
             a["motion"] in ("fixed", "platform", "target") and r["ratio"] is not None]
    return specs


def _streak_ratios(st, specs):
    return [st.ratio(s, "streak_length") for s in specs]


