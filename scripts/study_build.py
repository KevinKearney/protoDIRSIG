    c["size_min"] = (min(sizes), [])
    c["size_max"] = (max(sizes), [])
    dirsig_specs = [e for e in st.index.values() if not sm.is_satsim(e)]
    c["n_specs_dirsig"] = (len(dirsig_specs), [])
    c["n_specs_satsim_ctl"] = (sum(1 for e in st.index.values() if sm.is_satsim(e) and "control" in e), [])
    fams = {f: sum(1 for r in dirsig if r["family"] == f) for f in (1, 2, 3)}
    for f, n in fams.items():
        c[f"n_family{f}"] = (n, [])
    w = [st.attr[s]["window"] for s in st.attr]
    c["native_window"] = (s2s.NATIVE, [])
    c["small_window"] = (s2s.WINDOW, [])
    c["n_native"] = (sum(1 for x in w if x == s2s.NATIVE), [])
    c["n_small"] = (sum(1 for x in w if x == s2s.WINDOW), [])
    for k, v in st.sensor.items():
        c[k] = (v, [])
    c["rho"] = (s2s.REFLECTANCE, [])
    c["irradiance"] = (s2s.IRRADIANCE, [])
    c["bar_rho"] = (s2s.BAR_REFLECTANCE, [])
    c["bar_period_m"] = (s2s.BAR["period"], [])
    n = st.sensor["fnumber"]
    c["cone"] = (1.0 / (1.0 + 1.0 / (4.0 * n * n)), [])
    c["seed"] = (1, [])
    c["integration_samples"] = (s2s.INTEGRATION_SAMPLES, [])
    c["dirsig_version"] = (st.risk["E/lightcurve1-cube150-t1-a-vs-t2-a"]["tools"]["dirsig"], [])
    c["full_pixel_5ms"] = (st.s2s[HYPER_RANGE[1]]["full_pixel"], [HYPER_RANGE[1]])
    c["hyper_px"] = (cov.HYPER_PX, [])
    c["resolved_px"] = (cov.RESOLVED_PX, [])
    c["min_px"] = (env.MIN_PX, [])
    c["min_sweep_px"] = (env.MIN_SWEEP_PX, [])
    c["quiet"] = (env.QUIET, [])
    c["satsim_version"] = ("0.26.1", [])
    # hyperresolved
    lo, hi = _min_max_ratio(st, HYPER_RANGE)
    c["hyper_range_lo"], c["hyper_range_hi"] = (lo, HYPER_RANGE), (hi, HYPER_RANGE)
    c["hyper_side_lo"] = (s2s.PLATES["hyperresolved"]["side"] / s2s.footprint(100000.0), [])
    c["hyper_side_hi"] = (s2s.PLATES["hyperresolved"]["side"] / s2s.footprint(12500.0), [])
    ph = phase_hyper_native(st)
    lo, hi = _min_max_ratio(st, ph)
    c["phase_hyper_lo"], c["phase_hyper_hi"] = (lo, ph), (hi, ph)
    split = ["s2s3-phase-hyperresolved-a60-l0-z60", "s2s3-phase-hyperresolved-a60-l30-z30",
             "s2s3-phase-hyperresolved-a60-l60-z0"]
    vals = [st.ratio(s) for s in split]
    c["split_spread"] = (max(vals) - min(vals), split)
    for name, key in (("window_hyper", "hyper"), ("window_resolved", "resolved"), ("window_unres", "unres")):
        c[name] = _window(st, key)
