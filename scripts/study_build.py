    c["det_td_maxrel"] = (max(m(td, "max_rel")), td)
    c["det_td_minrel"] = (min(m(td, "max_rel")), td)
    c["det_td_px_lo"], c["det_td_px_hi"] = (min(m(td, "pixels_differing")), td), (max(m(td, "pixels_differing")), td)
    c["det_lit"] = (e[td[0]]["measured"]["pixels_lit"], td)
    c["det_td_sum"] = (max(m(td, "image_sum_rel_diff")), td)
    c["det_td_lc"] = (max(m(td, "lightcurve_last_rel_diff")), td)
    c["det_td_frac"] = (max(m(td, "fraction_differing")), td)
    c["det_fo_maxrel"] = (max(m(fo, "max_rel")), fo)
    c["det_fo_sum"] = (max(m(fo, "image_sum_rel_diff")), fo)
    c["det_n_pairs"] = (len(e), list(e))
    c["det_n_identical"] = (len(same), same)
    c["det_samples"] = (e[td[0]]["measured"]["samples"], td)
    c["det_outputs"] = (e[td[0]]["measured"]["outputs_compared"], td)
    a = [k for k in st.risk if k.startswith("A/")]
    c["home_equal"] = (sum(1 for k in a if st.risk[k]["measured"]["digests_equal"]), a)
    c["home_writes"] = (sum(st.risk[k]["measured"]["home_writes"] for k in a), a)
    c["n_home"] = (len(a), a)
    c["n_home_words"] = (WORDS[len(a)].capitalize(), a)
    b = [k for k in st.risk if k.startswith("B/") and "limit" not in k]
