# --- the template ---------------------------------------------------------------------------------------------------

FIELD = re.compile(r"\{\{([a-z]+):([^|}]+)(?:\|([^}]*))?\}\}")


def resolve(st, kind, key, spec, comp):
    """(text, [record ids]) of one field."""
    spec = spec or ""
    if kind == "r":
        parts = key.split(":")
        r = st.s2s[parts[0]]
        m = measurement(r, parts[1] if len(parts) > 1 else None)
        return fmt(m[parts[2] if len(parts) > 2 else "ratio"], spec), [parts[0]]
    if kind == "k":
        rid, path = key.split(":", 1)
        v = st.risk[rid]["measured"]
        for p in path.split("."):
            v = v[p]
        return fmt(v, spec), [rid]
    if kind == "d":
        row = st.doc[key]
        v = row["value"]
        if spec:
            v = fmt(float(v), spec)
        return v, [f"doc:{key}"]
    if kind == "c":
        v, ids = comp[key]
        return fmt(v, spec), ids
    if kind == "t":
        return TABLES[key](st), [f"table:{key}"]
    if kind == "n":
        return str(comp["_numbers"][key]), [f"table:{key}"]
    raise ValueError(f"unknown field kind {kind!r}")


def render(st, template=None):
    """(manuscript text, [(section, field, value, ids)])."""
    template = TEMPLATE.read_text() if template is None else template
    comp = computed(st)
    comp["_numbers"] = {name: i for i, name in enumerate(dict.fromkeys(re.findall(r"\{\{t:([a-z_]+)", template)), 1)}
    used = []
    out = []
    section = ""
    for line in template.splitlines(keepends=True):
        if line.startswith("#"):
            section = re.sub(r"\s*\{#[^}]*\}", "", line.strip("# \n"))

        def sub(mo):
            text, ids = resolve(st, mo.group(1), mo.group(2), mo.group(3), comp)
            used.append((section, mo.group(0), text, ids))
            return text.rstrip("\n") if mo.group(1) == "t" else text
        out.append(FIELD.sub(sub, line))
    text, note = "".join(out), GENERATED.format(src="manuscript.template.md")
    if text.startswith("---\n"):                                               # pandoc's metadata block stays first
        end = text.index("\n---\n", 4) + 5
        return text[:end] + "\n" + note + text[end:], used
    return note + text, used


def stray_numbers(template=None):
    """[(line number, text)] of digits in the template outside fields, code spans, math, comments and LEXICON."""
    template = TEMPLATE.read_text() if template is None else template
    text = re.sub(r"<!--.*?-->", lambda m: "\n" * m.group(0).count("\n"), template, flags=re.S)
    text = re.sub(r"\$\$.*?\$\$", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    out = []
    in_yaml = False
    for i, line in enumerate(text.splitlines(), 1):
        if i == 1 and line.strip() == "---":
            in_yaml = True
            continue
        if in_yaml:
            in_yaml = line.strip() != "---"
            line = re.sub(r"^\s*[a-z-]+:", "", line)
        s = FIELD.sub(" ", line)
        s = re.sub(r"`[^`]*`", " ", s)
        s = re.sub(r"\$[^$]+\$", " ", s)
        s = re.sub(r"\]\([^)]*\)", "]", s)                                      # link targets
        s = re.sub(r"^#+\s+(?:[A-Z]?\d+(?:\.\d+)*\.?)?", "", s)                  # heading numbers
        s = re.sub(r"\{#[^}]*\}", " ", s)
        for word in LEXICON:
            s = s.replace(word, " ")
        if re.search(r"\d", s):
            out.append((i, line.strip()))
    return out


def outputs(st):
    """{path: text} of every generated file but the data appendix."""
    out = {}
    for name, fn in TABLES.items():
        out[TABLES_DIR / f"{name}.md"] = GENERATED.format(src="the records") + fn(st)
    text, _ = render(st)
    out[MANUSCRIPT] = text
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fields", action="store_true", help="print every field with its value and record ids")
    args = ap.parse_args(argv)
    stray = stray_numbers()
    if stray:
        for i, line in stray:
            print(f"manuscript.template.md:{i}: a number outside a field: {line[:120]}", file=sys.stderr)
        return 1
    rows = consolidate()
    for path, text in data_files(rows).items():
        if not args.fields:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    st = Study(json.loads(json.dumps(rows)))
    if args.fields:
        _, used = render(st)
        for section, field, text, ids in used:
            if not field.startswith("{{t:"):
                print(f"{section}\t{field}\t{text}\t{' '.join(ids[:3])}")
        return 0
    for path, text in outputs(st).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(rows)} consolidated records, {len(TABLES)} tables and {MANUSCRIPT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
