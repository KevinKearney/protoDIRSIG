#!/usr/bin/env python3
"""The space-to-space study (`docs/study/`): its tables and its manuscript, every number generated from the records.

    python scripts/study_build.py             write the tables and the manuscript
    python scripts/study_build.py --fields    print every field of the template with its value and record ids

Inputs: the DIRSIG and SatSim records (`docs/data/s2s_results.jsonl`, `scripts/s2s_measure.py`), the known-risk records
(`docs/data/risk_measurements.jsonl`, `scripts/risk_measure.py`), the figures that committed documents state but no
record holds (`docs/study/data/document_figures.csv`: scratch controls of rounds 29 to 40 and the determinism probe),
the specs' index and sensor-spec (`scripts/s2s_scenarios.py`), the envelope's grouping (`scripts/s2s_envelope.py`) and
the regression tolerances (`tests/test_s2s_results.py`).

The manuscript is `docs/study/manuscript.template.md` with named fields, written to `docs/study/manuscript.md`. A field
is `{{KIND:KEY|FORMAT}}`:

- `r:SPEC` the record's primary ratio; `r:SPEC:METHOD` a further measurement's ratio; `r:SPEC:METHOD:FIELD` its
  `measured`, `expected` or `ratio`;
- `k:RISK/ID:PATH` a value in a known-risk record's `measured` (`PATH` dotted);
- `d:ID` a figure of `document_figures.csv`;
- `c:NAME` a value computed here (`COMPUTED`), with the record ids it reads;
- `t:NAME` a table (`TABLES`), written to `docs/study/tables/NAME.md` and inlined; `n:NAME` its number, in the order
  of first appearance (pandoc numbers captioned tables in the same order).

`FORMAT` is a Python format specification, optionally after a transform and a colon: `def` (100 (1 - x), a deficit in
percent), `exc` (100 (x - 1)), `pct` (100 x), `abs` (|x|), `rel` (|x - 1|). Numbers in the template's prose outside a
field, a code span or a math span are refused (`stray_numbers`), except the names in `LEXICON`.
"""
