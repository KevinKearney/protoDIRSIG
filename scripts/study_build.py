    c["bg_box"] = (100, [])                     # s2s_measure.reduce: family III's background group, a[200:300, 200:300]
    c["seed2"], c["seed3"] = (2, []), (3, [])   # the scratch seeds of round 30 (document_figures.csv)
    c["seed_range_lo"] = (st.rng(HYPER_RANGE[2]) / 1000, [HYPER_RANGE[2]])
    c["seed_range_hi"] = (st.rng(HYPER_RANGE[3]) / 1000, [HYPER_RANGE[3]])
