    c["plate_small"] = (s2s.PLATES["unresolved"]["side"], [])
    c["speed_lo"], c["speed_hi"] = (min(s2s.MOVING), []), (max(s2s.MOVING), [])
    c["sphere_hyper"] = (s2s.SPHERES["hyperresolved"][0], [])
    c["sphere_small"] = (s2s.SPHERES["unresolved"][0], [])
    c["sphere_range_km"] = (st.rng("s2s3-phase-unresolved-a0-l0-z0") / 1000, ["s2s3-phase-unresolved-a0-l0-z0"])
