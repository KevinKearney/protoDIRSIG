def _range_km(st, spec):
    r = st.rng(spec)
    return "-" if r is None else f"{r / 1000:g}"


def t_cases(st):
    """Appendix A: every spec of the index by family and group, with its axes and how many are recorded."""
    groups = {}
    for name, e in st.index.items():
        fam = sm.family(e)
        p = sm.point(e)
        if fam == 1:
            key = ("I", p["object_class"].replace("_", " "))
        elif fam in (2, 3):
            key = ({2: "II", 3: "III"}[fam], p["group"].replace("_", " "))
        elif "control" in e:
            key = ("SatSim control", f"{e['control']}, {e['target']}")
        else:
            key = ("SatSim parity", "sphere and plate")
        g = groups.setdefault(key, {"specs": 0, "recorded": 0, "range": set(), "exp": set(), "look": set(),
                                    "zen": set(), "speed": set(), "offset": set(), "window": set()})
        g["specs"] += 1
        g["recorded"] += name in st.s2s
        if fam in (1, 2, 3) or "control" in e:
            r = st.rng(name) if fam in (1, 2, 3) else p.get("range_m")
            if r:
                g["range"].add(round(r / 1000, 3))
            if p.get("exposure_s") is not None:
                g["exp"].add(round(p["exposure_s"] * 1000, 3))
            elif fam == 3:
                g["exp"].add(5.0)
            if p.get("look_deg") is not None:
                g["look"].add(p["look_deg"])
            if p.get("solar_zenith_deg") is not None:
                g["zen"].add(p["solar_zenith_deg"])
            sp = p.get("relative_speed")
            if isinstance(sp, float):
                g["speed"].add(sp)
            elif fam == 2 and p["group"] in ("platform", "target", "both"):
                g["speed"].add({"platform": 1000.0, "target": 1000.0, "both": 2000.0}[p["group"]])
            if p.get("offset_px") is not None:
                g["offset"].add(p["offset_px"])
            g["window"].add(p.get("window", s2s.NATIVE))
    j = lambda s: ", ".join(f"{v:g}" for v in sorted(s)) or "-"                # noqa: E731
    rows = [(f, grp, g["specs"], g["recorded"], j(g["range"]), j(g["exp"]), j(g["look"]), j(g["zen"]), j(g["speed"]),
             j(g["offset"]), j(g["window"])) for (f, grp), g in sorted(groups.items(), key=lambda kv: (
                 ["I", "II", "III", "SatSim parity", "SatSim control"].index(kv[0][0]), kv[0][1]))]
    return md_table(("Family", "Group", "Specs", "Recorded", "Range (km)", "Exposure (ms)", "Look (deg)",
                     "Solar zenith (deg)", "Relative speed (m/s)", "Offset (px)", "Window (px)"), rows)


