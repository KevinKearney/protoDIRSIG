def tolerances():
    """{name: (value, the comment's case text)} of the regression tolerances, in file order."""
    text = TOL_SOURCE.read_text()
    out = {}
    for node in ast.parse(text).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name.startswith("TOL_") and isinstance(node.value, ast.Constant):
                line = text.splitlines()[node.lineno - 1]
                comment = line.split("#", 1)[1].strip() if "#" in line else ""
                out[name] = (node.value.value, comment)
    return out


def measurement(r, method=None):
    """The primary measurement of a record (method None) or its further measurement `method`, as a dict."""
    ms = [{k: r[k] for k in sm.MEASUREMENT_KEYS}] + list(r["also"])
    if method is None:
        return ms[0]
    m = next((m for m in ms if m["method"] == method), None)
    if m is None:
        raise KeyError(f"{r['spec']}: no {method}")
    return m


def sensor():
    doc = yaml.safe_load((s2s.SENSORS / s2s.SENSOR).read_text())
    e = doc["sensor"]["entries"][0]
    det = e["focal_planes"][0]["detector"]
    return {"aperture_mm": e["optics"]["aperture_diameter"], "focal_mm": e["optics"]["focal_length"],
            "fnumber": e["optics"]["f_number"], "tau": e["optics"]["throughput_in_band"]["value"],
            "pitch_um": det["SensorPixelWidth"]}


class Study:
    """Everything the tables and fields read, loaded once."""

    def __init__(self, rows=None):
        rows = load_consolidated() if rows is None else rows
        self.data = rows
        self.s2s = {r["id"]: r["record"] for r in rows if r["dataset"] == "s2s"}
        self.risk = {r["id"]: r["record"] for r in rows if r["dataset"] == "risk"}
        self.doc = document_figures()
        self.tol = tolerances()
        self.index = sm.index(controls=True)
        self.rows = env.rows_of_records()
        self.attr = {r["spec"]: a for r, a, _, _ in self.rows}
        self.excluded = {r["spec"]: why for r, _, _, why in self.rows if why}
        self.sensor = sensor()

    def ratio(self, spec, method=None):
        return measurement(self.s2s[spec], method)["ratio"]

    def rng(self, spec):
        """The record's range (m): the family point's, or its footprint over the pixel's angle."""
        return _range_of(spec, self.index[spec])


# --- formatting -----------------------------------------------------------------------------------------------------

TRANSFORMS = {"def": lambda x: 100 * (1 - x), "exc": lambda x: 100 * (x - 1), "pct": lambda x: 100 * x,
              "abs": abs, "rel": lambda x: abs(x - 1), "": lambda x: x}


def fmt(value, spec):
    """Format a value by `[transform:]spec`; a string passes through."""
    if isinstance(value, str):
        return value
    transform, _, spec = spec.rpartition(":") if ":" in spec else ("", "", spec)
    v = TRANSFORMS[transform](value)
    if spec == "sci":                                                           # 6.3e-06 -> 6.3e-6
        mant, exp = f"{v:.1e}".split("e")
        return f"{mant}e{int(exp)}"
    if spec == "sci2":
        mant, exp = f"{v:.2e}".split("e")
        return f"{mant}e{int(exp)}"
    if spec == "thou":
        return f"{v:,.0f}"
    out = format(v, spec or "g")
    return out[1:] if re.fullmatch(r"-0(\.0*)?", out) else out


def f4(x):
    return "-" if x is None else f"{x:.4f}"


def pct(d):
    return f"{100 * d:+.1f} %"


def pct_range(lo, hi):
    return pct(lo) if abs(hi - lo) < 5e-4 else f"{pct(lo)} to {pct(hi)}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


