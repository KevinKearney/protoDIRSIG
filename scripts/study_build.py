def record_commits(path, key):
    """{record id: short hash of the earliest commit that added a line holding it} from `git log -p` of `path`."""
    import subprocess
    try:
        log = subprocess.run(["git", "log", "--reverse", "--format=commit %h", "-p", "-U0", "--", str(path)], cwd=ROOT,
                             check=True, capture_output=True, text=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return {}
    out, commit = {}, None
    for line in log.splitlines():
        if line.startswith("commit "):
            commit = line.split()[1]
        elif line.startswith("+{"):
            try:
                rid = key(json.loads(line[1:]))
            except (ValueError, KeyError):
                continue
            out.setdefault(rid, commit)
    return out


def _round(source):
    m = SCRATCH_ROUND.search(source or "")
    return int(m.group(1)) if m else None


def reproduce_s2s(name, record):
    """{spec, scene, configuration, command} that regenerate an s2s record from the repository."""
    spec = yaml.safe_load((s2s.OUT / f"{name}.yaml").read_text())
    eng = spec["engine"]
    lib = s2s.LIBRARY.relative_to(ROOT).as_posix()
    if record["family"] == "satsim":
        scene = None
        conf = f"{lib}/{eng['config']['name']}"
    else:
        scene = f"{lib}/{eng['scenes'][0]['ref']['name']}"
        conf = f"{lib}/{eng['platform']['ref']['name']}; manifold_sensors/{spec['descriptor']['sensor']['ref']['name']}"
    cmd = S2S_COMMAND.format(name=name)
    if record["source"].endswith("--workspace"):
        cmd += " --via workspace"
    return {"spec": f"{s2s.OUT.relative_to(ROOT).as_posix()}/{name}.yaml", "scene": scene, "configuration": conf,
            "command": cmd}


def consolidate(records=None, risks=None, commits=None):
    """[row] of the consolidated data, s2s records then risk records, each a dict of `COLUMNS` plus `record`."""
    records = s2s_records() if records is None else records
    risks = risk_records() if risks is None else risks
    if commits is None:
        commits = {**{("s2s", k): v for k, v in record_commits(S2S, lambda r: r["spec"]).items()},
                   **{("risk", k): v for k, v in record_commits(RISK, lambda r: f"{r['risk']}/{r['id']}").items()}}
    index = sm.index(controls=True)
    rows_env = {r["spec"]: (a, key, why) for r, a, key, why in env.rows_of_records()}
    out = []
    for name, r in sorted(records.items()):
        e = index[name]
        row = dict.fromkeys(COLUMNS)
        row.update(dataset="s2s", id=name, family=str(r["family"]),
                   engine="satsim" if r["family"] == "satsim" else "dirsig", run_id=r["run_id"],
                   round=_round(r["source"]), commit=commits.get(("s2s", name)), source=r["source"],
                   method=r["method"], measured=r["measured"], expected=r["expected"], ratio=r["ratio"],
                   product_sha256=next(iter(r["product"].values())))
        if name in rows_env:
            a, key, why = rows_env[name]
            row.update(shape=a["shape"], size_px=a["size_px"], size_class=a["size_class"], labelled=a["labelled"],
                       motion=a["motion"], exposure_ms=a["exposure_s"] * 1000, look_deg=a["look_deg"],
                       solar_zenith_deg=a["solar_zenith_deg"], offset_px=a["offset_px"], window_px=a["window"],
                       envelope_row=" / ".join(str(k) for k in key) if key else None, excluded_reason=why)
        else:                                                                   # a SatSim control
            p = sm.point(e)
            row.update(shape=p["target"], size_px=p["size_m"] / s2s.footprint(p["range_m"]), motion=(
                "target" if p["relative_speed"] else "fixed"), exposure_ms=p["exposure_s"] * 1000,
                look_deg=p["look_deg"], offset_px=p["offset_px"], window_px=p["window"], labelled=None)
        rng = _range_of(name, e)
        row["range_km"] = None if rng is None else rng / 1000
        for m in r["also"]:
            if m["method"] == "streak_length":
                row.update(streak_measured_px=m["measured"], streak_expected_px=m["expected"], streak_ratio=m["ratio"])
            elif m["method"] == "half_level_count":
                row["half_level_ratio"] = m["ratio"]
            elif m["method"] == "peak":
                row["peak_ratio"] = m["ratio"]
            elif m["method"] == "centre_offset_px":
                row["centre_offset_px"] = m["measured"]
        rep_ = reproduce_s2s(name, r)
        row.update(reproduce_spec=rep_["spec"], reproduce_scene=rep_["scene"],
                   reproduce_configuration=rep_["configuration"], reproduce_command=rep_["command"],
                   relay_host="yes", relay_host_reason="one render alone, one thread; the native 500 x 500 renders "
                   "take up to a few minutes and the 64 x 64 ones seconds")
        out.append({**row, "record": r, "reproduce": rep_})
    for rid, k in sorted(risks.items()):
        conf, cmd, relay, why = RISK_REPRODUCE[k["risk"]]
        row = dict.fromkeys(COLUMNS)
        row.update(dataset="risk", id=rid, family=k["risk"], engine="dirsig", round=_round(k["source"]),
                   commit=commits.get(("risk", rid)), source=k["source"], method=k["method"],
                   reproduce_configuration=conf, reproduce_command=cmd, relay_host=relay, relay_host_reason=why,
                   risk_measured=json.dumps(k["measured"], sort_keys=True))
        if k["risk"] == "B" and relay == "partly":
            n = k["measured"].get("n")
            row["relay_host"] = "no" if (n or 0) > 4 else "yes"
        out.append({**row, "record": k,
                    "reproduce": {"spec": None, "scene": None, "configuration": conf, "command": cmd}})
    return out


def _range_of(name, entry):
    p = sm.point(entry)
    if isinstance(p.get("range_m"), float):
        return p["range_m"]
    fam = sm.family(entry)
    if fam == 2 and p["kind"] in ("blur", "look"):
        return s2s.expected2(p)["footprint_m"] / s2s.footprint(1.0)
    if fam == 3:
        return s2s.expected3(p)["footprint_m"] / s2s.footprint(1.0)
    return None


def data_files(rows):
    """{path: text} of the consolidated JSONL and CSV."""
    import io
    jl = "".join(json.dumps(r, sort_keys=False) + "\n" for r in rows)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(COLUMNS)
    for r in rows:
        w.writerow(["" if r[c] is None else (repr(r[c]) if isinstance(r[c], float) else r[c]) for c in COLUMNS])
    return {STUDY_JSONL: jl, STUDY_CSV: buf.getvalue()}


def load_consolidated(path=STUDY_JSONL):
    """[row] of the committed consolidated data."""
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


